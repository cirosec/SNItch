#!/usr/bin/env python3
"""Render the SNItch test environment from sites.json.

This is the single rendering step shared by the nginx and Caddy stacks. It
produces, under testenv/generated/:

  * certs.manifest        - certificate inventory consumed by generate-certs.sh
  * dns/dnsmasq.conf      - forward/reverse records + wildcard zones
  * nginx/nginx.conf      - main nginx config
  * nginx/conf.d/*.conf   - one server block file per bound IP
  * caddy/Caddyfile       - equivalent Caddy config
  * snitch-targets.txt    - target list for SNItch (ip:443 per line)
  * snitch-hosts.txt      - host list for SNItch (one hostname per line)
  * snitch-targets-hardened.txt     - IP-only targets that must reveal nothing
  * snitch-targets-header-leak.txt  - IP-only header-leak targets for the
                                       --search-headers discovery test

The output is deterministic so the nginx and Caddy environments stay in sync.
"""

from __future__ import annotations

import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TESTENV = os.path.dirname(HERE)
GENERATED = os.path.join(TESTENV, "generated")


def load_sites() -> dict:
    with open(os.path.join(TESTENV, "sites.json"), "r", encoding="utf-8") as fh:
        return json.load(fh)


def write(path: str, content: str) -> None:
    full = os.path.join(GENERATED, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"  [render] generated/{path}")


def is_ip(value: str) -> bool:
    parts = value.split(".")
    if len(parts) != 4:
        return False
    try:
        return all(0 <= int(p) <= 255 for p in parts)
    except ValueError:
        return False


def html(title: str) -> str:
    # No single quotes and no '$' so it is safe inside an nginx single-quoted
    # string and unambiguous for the SNItch title extractor.
    return f"<!doctype html><html><head><title>{title}</title></head><body>{title}</body></html>"


# --------------------------------------------------------------------------- #
# Certificate manifest
# --------------------------------------------------------------------------- #

def render_cert_manifest(sites: dict) -> None:
    lines = []
    for cert in sites["certificates"]:
        sans = ",".join(cert.get("sans", []))
        ips = ",".join(cert.get("ips", []))
        expired = "expired" if cert.get("expired") else ""
        lines.append(f"{cert['name']}|{sans}|{ips}|{expired}")
    write("certs.manifest", "\n".join(lines) + "\n")


# --------------------------------------------------------------------------- #
# DNS
# --------------------------------------------------------------------------- #

def render_dnsmasq(sites: dict) -> None:
    dns = sites["dns"]
    out = [
        "# generated by scripts/render.py - do not edit",
        f"port={dns['port']}",
        f"listen-address={dns['listen']}",
        "bind-interfaces",
        "no-resolv",
        "no-hosts",
        "log-facility=-",
        "domain-needed",
        "bogus-priv",
        "# Never forward the reserved .test TLD upstream: unknown .test names get",
        "# NXDOMAIN so unresolved hosts stay unresolved (hermetic).",
        "local=/test/",
        "",
        "# ---- static forward records (host-record also creates PTR) ----",
    ]

    wildcard_zones: dict[str, set[str]] = {}
    for server in sites["servers"]:
        if server.get("no_dns"):
            # Hardened servers are deliberately absent from DNS/PTR so that an
            # IP-only scan cannot discover anything.
            continue
        ip = server["ip"]
        for site in server["sites"]:
            for name in site["server_names"]:
                if name.startswith("*."):
                    wildcard_zones.setdefault(name[2:], set()).add(ip)
                elif is_ip(name):
                    continue
                elif site.get("no_dns"):
                    # Names that must stay out of DNS (e.g. cert-only
                    # discovery scenarios) are skipped here.
                    continue
                else:
                    out.append(f"host-record={name},{ip}")

    if wildcard_zones:
        out.append("")
        out.append("# ---- wildcard zones ----")
        for zone, ips in sorted(wildcard_zones.items()):
            for ip in sorted(ips):
                out.append(f"address=/{zone}/{ip}")

    out.append("")
    out.append("# ---- upstream resolvers for everything else ----")
    for upstream in dns.get("upstream", []):
        out.append(f"server={upstream}")
    out.append("")

    write("dns/dnsmasq.conf", "\n".join(out))


# --------------------------------------------------------------------------- #
# nginx
# --------------------------------------------------------------------------- #

NGINX_MAIN = """\
# generated by scripts/render.py - do not edit
worker_processes auto;
error_log /dev/stderr info;
pid /var/run/nginx.pid;

events {
    worker_connections 1024;
}

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    access_log /dev/stdout;

    sendfile on;
    keepalive_timeout 30;

    # The scanner negotiates down to TLS 1.0; a real server would be stricter.
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:SSL:10m;
    ssl_session_tickets off;

    include /etc/nginx/conf.d/*.conf;
}
"""


def nginx_port80(server: dict) -> str:
    ip = server["ip"]
    if server.get("no_http"):
        return f"""\
# Plaintext HTTP: answer nothing (close the connection) so the probe reveals
# no hostname.
server {{
    listen {ip}:80 default_server;
    server_name _;
    return 444;
}}
"""
    leak = server.get("http_header_leak")
    if leak:
        headers = "\n".join(
            f'    add_header {name} "{value}" always;' for name, value in leak.items()
        )
        title = server.get("http_title", "Header Leak Service")
        return f"""\
# Plaintext HTTP: a normal response whose body names no host, but which leaks
# the canonical hostname in a response header. Only --search-headers extracts
# hostnames from headers other than Location, so the default probes here reveal
# nothing and only the header search discovers the vhost on this hardened IP.
server {{
    listen {ip}:80 default_server;
    server_name _;
{headers}
    default_type text/html;
    return 200 '{html(title)}';
}}
"""
    redirect = server["http_redirect"]
    return f"""\
# Plaintext HTTP: catch-all that redirects every Host to the canonical host,
# which reveals {redirect} to the plaintext HTTP probe.
server {{
    listen {ip}:80 default_server;
    server_name _;
    return 301 {redirect}$request_uri;
}}
"""


def nginx_fallback_block(ip: str, cert: str, title: str) -> str:
    return f"""\
# Fallback TLS server: answers unknown and absent SNI with the fallback
# certificate (so random SNI does NOT disconnect).
server {{
    listen {ip}:443 ssl default_server;
    server_name _;
    ssl_certificate     /etc/nginx/certs/{cert}.crt;
    ssl_certificate_key /etc/nginx/certs/{cert}.key;
    default_type text/html;
    return 200 '{html(title)}';
}}
"""


def nginx_strict_block(ip: str) -> str:
    return f"""\
# SNI-strict default server: reject unknown and absent SNI with a TLS alert.
server {{
    listen {ip}:443 ssl default_server;
    server_name _;
    ssl_reject_handshake on;
}}
"""


def nginx_site_block(ip: str, site: dict) -> str:
    names = " ".join(site["server_names"])
    cert = site["cert"]
    port = site.get("port", 443)
    common = f"""\
server {{
    listen {ip}:{port} ssl;
    server_name {names};
    ssl_certificate     /etc/nginx/certs/{cert}.crt;
    ssl_certificate_key /etc/nginx/certs/{cert}.key;
"""
    status = site.get("status", 200)
    if 300 <= status < 400 and site.get("redirect"):
        return common + f"    return {status} {site['redirect']};\n}}\n"
    title = site.get("title", names.split()[0])
    return common + f"    default_type text/html;\n    return {status} '{html(title)}';\n}}\n"


def render_nginx(sites: dict) -> None:
    write("nginx/nginx.conf", NGINX_MAIN)
    for server in sites["servers"]:
        ip = server["ip"]
        parts = [
            f"# generated by scripts/render.py - do not edit",
            f"# {ip} - {server['role']}: {server.get('description', '')}",
            "",
            nginx_port80(server),
        ]
        if server.get("fallback_cert"):
            title = server.get("fallback_title", f"{server['role'].capitalize()} Service")
            parts.append(nginx_fallback_block(ip, server["fallback_cert"], title))
        else:
            parts.append(nginx_strict_block(ip))
        for site in server["sites"]:
            parts.append(nginx_site_block(ip, site))
        write(f"nginx/conf.d/{ip}.conf", "\n".join(parts))


# --------------------------------------------------------------------------- #
# Caddy
# --------------------------------------------------------------------------- #

CADDY_GLOBAL = """\
# generated by scripts/render.py - do not edit
{
	admin off
	# All certificates are explicit; never attempt ACME. We define the
	# plaintext HTTP behaviour ourselves, so disable the automatic redirect.
	auto_https disable_redirects
	log {
		output stderr
		format console
	}
}
"""


def caddy_site_block(server: dict, site: dict) -> str:
    ip = server["ip"]
    names = site["server_names"]
    port = site.get("port", 443)
    prefix = "https://"
    addresses = ", ".join(prefix + (n if port == 443 else f"{n}:{port}") for n in names)
    cert = site["cert"]
    head = (
        f"{addresses} {{\n"
        f"\tbind {ip}\n"
        f"\ttls /etc/caddy/certs/{cert}.crt /etc/caddy/certs/{cert}.key\n"
    )
    status = site.get("status", 200)
    if 300 <= status < 400 and site.get("redirect"):
        return head + f"\tredir {site['redirect']} {status}\n}}\n"
    title = site.get("title", names[0])
    body = json.dumps(html(title))
    return (
        head
        + '\theader Content-Type "text/html; charset=utf-8"\n'
        + f"\trespond {body} {status}\n}}\n"
    )


def render_caddy(sites: dict) -> None:
    # One Caddy instance per bound IP. Caddy selects certificates from a
    # process-global cache, so a single instance would serve any loaded
    # certificate on any listener and break the per-IP isolation (notably the
    # hardened server). Separate instances keep each IP's certificate set
    # isolated, matching nginx's per-listener SNI routing.
    for server in sites["servers"]:
        ip = server["ip"]
        parts = [CADDY_GLOBAL]
        parts.append(f"# ===== {ip} - {server['role']}: {server.get('description', '')} =====")
        parts.append("")
        # Plaintext HTTP behaviour.
        if server.get("no_http"):
            parts.append(
                "# Plaintext HTTP: answer nothing (close the connection) so the\n"
                "# probe reveals no hostname.\n"
                "http://:80 {\n"
                f"\tbind {ip}\n"
                "\tabort\n"
                "}\n"
            )
        elif server.get("http_header_leak"):
            leak = server["http_header_leak"]
            headers = "\n".join(
                f"\theader {name} {json.dumps(value)}" for name, value in leak.items()
            )
            body = json.dumps(html(server.get("http_title", "Header Leak Service")))
            parts.append(
                "# Plaintext HTTP: a normal page whose body names no host, but\n"
                "# which leaks the canonical hostname in a response header. Only\n"
                "# --search-headers parses headers other than Location.\n"
                "http://:80 {\n"
                f"\tbind {ip}\n"
                f"{headers}\n"
                f"\trespond {body} 200\n"
                "}\n"
            )
        else:
            parts.append(
                "http://:80 {\n"
                f"\tbind {ip}\n"
                f"\tredir {server['http_redirect']}{{uri}} 301\n"
                "}\n"
            )
        if server.get("fallback_cert"):
            title = server.get("fallback_title", f"{server['role'].capitalize()} Service")
            body = json.dumps(html(title))
            parts.append(
                "# Catch-all HTTPS site: serves the fallback certificate for\n"
                "# unknown/absent SNI so the handshake does not fail.\n"
                "https:// {\n"
                f"\tbind {ip}\n"
                f"\ttls /etc/caddy/certs/{server['fallback_cert']}.crt /etc/caddy/certs/{server['fallback_cert']}.key\n"
                '\theader Content-Type "text/html; charset=utf-8"\n'
                f"\trespond {body} 200\n"
                "}\n"
            )
        for site in server["sites"]:
            parts.append(caddy_site_block(server, site))
        write(f"caddy/{ip}.Caddyfile", "\n".join(parts))


# --------------------------------------------------------------------------- #
# SNItch inputs
# --------------------------------------------------------------------------- #

def render_snitch_inputs(sites: dict) -> None:
    targets = []
    hosts: set[str] = set()
    for server in sites["servers"]:
        ip = server["ip"]
        targets.append(f"{ip}:443")
        if server.get("fallback_cert"):
            hosts.add(server["fallback_cert"])
        for site in server["sites"]:
            port = site.get("port", 443)
            if port != 443:
                targets.append(f"{ip}:{port}")
            for name in site["server_names"]:
                if is_ip(name):
                    continue
                if server.get("no_dns") or site.get("no_dns") or site.get("no_supply"):
                    # Not supplied: SNItch must discover the name itself
                    # (redirect chain, certificate SAN, HTTP header leak).
                    continue
                hosts.add(name)
    write("snitch-targets.txt", "\n".join(targets) + "\n")
    write("snitch-hosts.txt", "\n".join(sorted(hosts)) + "\n")

    # Targets that must yield no findings on an IP-only scan (hardened servers).
    hardened = [
        f"{s['ip']}:443" for s in sites["servers"] if s.get("expect_no_findings")
    ]
    write("snitch-targets-hardened.txt", "\n".join(hardened) + "\n")

    # Targets whose plaintext HTTP service leaks the canonical hostname in a
    # response header. A default IP-only scan reveals nothing; a scan with
    # --search-headers discovers the vhost. Drives the header-leak test.
    header_leak = [
        f"{s['ip']}:443" for s in sites["servers"] if s.get("http_header_leak")
    ]
    write("snitch-targets-header-leak.txt", "\n".join(header_leak) + "\n")


def main() -> int:
    sites = load_sites()
    # Clear previous output so removed servers/certs do not leave stale files.
    shutil.rmtree(GENERATED, ignore_errors=True)
    os.makedirs(GENERATED, exist_ok=True)
    render_cert_manifest(sites)
    render_dnsmasq(sites)
    render_nginx(sites)
    render_caddy(sites)
    render_snitch_inputs(sites)
    return 0


if __name__ == "__main__":
    sys.exit(main())
